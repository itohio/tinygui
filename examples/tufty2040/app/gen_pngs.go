//go:build ignore

// Generates pngs.go: four 20×20 PNG icons as string constants for widget.Icon
// (TinyGUI decodes PNG at draw time with tinygo.org/x/drivers/image/png).
//
//	go run gen_pngs.go > pngs.go
package main

import (
	"bytes"
	"fmt"
	"image"
	"image/color"
	"image/png"
	"math"
	"os"
)

const size = 20

type shape func(x, y float64) bool

func main() {
	icons := []struct {
		name string
		bg   color.RGBA
		in   shape
	}{
		{"Circle", color.RGBA{0, 150, 170, 255}, func(x, y float64) bool { return x*x+y*y < 0.45 }},
		{"Heart", color.RGBA{200, 50, 80, 255}, func(x, y float64) bool {
			y = -y + 0.15
			a := x*x + y*y - 0.35
			return a*a*a-x*x*y*y*y < 0
		}},
		{"Star", color.RGBA{220, 150, 20, 255}, func(x, y float64) bool {
			r := math.Hypot(x, y)
			a := math.Atan2(y, x) + math.Pi/2
			k := math.Cos(5*a)*0.22 + 0.48
			return r < k
		}},
		{"Check", color.RGBA{40, 160, 80, 255}, func(x, y float64) bool {
			d1 := math.Abs((y-0.1)-(x+0.35)*0.9) < 0.14 && x > -0.55 && x < -0.05
			d2 := math.Abs((y-0.1)+(x+0.05)*1.4) < 0.14 && x > -0.12 && x < 0.6
			return d1 || d2
		}},
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by gen_pngs.go; DO NOT EDIT.")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "package app")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "const pngSize = %d\n\n", size)
	var names []string
	for _, ic := range icons {
		img := image.NewRGBA(image.Rect(0, 0, size, size))
		for py := range size {
			for px := range size {
				x := (float64(px)+0.5)/size*2 - 1
				y := (float64(py)+0.5)/size*2 - 1
				c := ic.bg
				if math.Abs(x) > 0.92 && math.Abs(y) > 0.92 { // clipped corners
					c = color.RGBA{26, 30, 42, 255}
				} else if ic.in(x, -y) {
					c = color.RGBA{250, 250, 250, 255}
				}
				img.SetRGBA(px, py, c)
			}
		}
		var b bytes.Buffer
		if err := png.Encode(&b, img); err != nil {
			panic(err)
		}
		fmt.Fprintf(&out, "const png%s = %q\n\n", ic.name, b.String())
		names = append(names, "png"+ic.name)
	}
	fmt.Fprintln(&out, "var pngIcons = []string{")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%s,\n", n)
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "var pngNames = []string{\"circle\", \"heart\", \"star\", \"check\"}")
	os.Stdout.Write(out.Bytes())
}
